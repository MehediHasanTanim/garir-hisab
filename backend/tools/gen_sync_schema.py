#!/usr/bin/env python3
"""Generates the Supabase sync schema from the app's Drift schema snapshot.

    python3 backend/tools/gen_sync_schema.py app/drift_schemas/app/drift_schema_v5.json \
        > backend/supabase/migrations/<timestamp>_sync_schema.sql

Every synced table gets the same columns as on the phone (minus the local-only
`dirty` flag) plus `server_seq`, a server-assigned, ever-increasing number that
sync clients use as their pull cursor.
"""
import json
import sys

LOCAL_ONLY = {"daily_rollups", "audit_logs", "sync_meta", "sync_issues"}
SQL_TYPES = {"string": "text", "int": "bigint", "bool": "boolean"}


def main(path: str) -> None:
    snapshot = json.load(open(path))
    tables = [
        e["data"]
        for e in snapshot["entities"]
        if e["type"] == "table" and e["data"]["name"] not in LOCAL_ONLY
    ]
    names = [t["name"] for t in tables]

    print("-- GENERATED by backend/tools/gen_sync_schema.py. Do not edit by hand.")
    print("-- Sync schema: one table per synced app table, with RLS and server_seq.\n")
    print("create sequence if not exists public.sync_seq;\n")
    print("""create or replace function public.sync_stamp() returns trigger
language plpgsql as $$
begin
  new.server_seq := nextval('public.sync_seq');
  -- Never trust a phone clock more than a day ahead of the server.
  new.updated_at := least(
    new.updated_at,
    (extract(epoch from now()) * 1000)::bigint + 86400000
  );
  if tg_op = 'UPDATE' then
    new.owner_id := old.owner_id;
  end if;
  return new;
end;
$$;
""")

    for t in tables:
        name = t["name"]
        cols = [c for c in t["columns"] if c["name"] != "dirty"]
        print(f"create table public.{name} (")
        lines = []
        for c in cols:
            n = c["name"]
            if n == "owner_id":
                lines.append(
                    "  owner_id uuid not null default auth.uid() "
                    "references auth.users (id) on delete cascade"
                )
            elif n == "id":
                lines.append("  id text primary key")
            else:
                sql = SQL_TYPES[c["moor_type"]]
                null = "" if c["nullable"] else " not null"
                default = ""
                if not c["nullable"] and n in ("rev",):
                    default = " default 0"
                lines.append(f"  {n} {sql}{null}{default}")
        lines.append("  server_seq bigint not null default nextval('public.sync_seq')")
        for uk in t.get("unique_keys") or []:
            lines.append(f"  unique ({', '.join(uk)})")
        print(",\n".join(lines))
        print(");\n")
        print(f"create index {name}_owner_seq on public.{name} (owner_id, server_seq);")
        print(f"alter table public.{name} enable row level security;")
        for op, clause in (
            ("select", "using (owner_id = auth.uid())"),
            ("insert", "with check (owner_id = auth.uid())"),
            ("update", "using (owner_id = auth.uid()) with check (owner_id = auth.uid())"),
        ):
            print(
                f"create policy {name}_{op}_own on public.{name} "
                f"for {op} to authenticated {clause};"
            )
        print(
            f"create trigger {name}_stamp before insert or update on public.{name} "
            "for each row execute function public.sync_stamp();\n"
        )

    quoted = ", ".join(f"'{n}'" for n in names)
    print(f"""-- The tables clients may sync.
create or replace function public.sync_tables() returns text[]
language sql immutable as $$ select array[{quoted}]::text[] $$;
""")


if __name__ == "__main__":
    main(sys.argv[1])
